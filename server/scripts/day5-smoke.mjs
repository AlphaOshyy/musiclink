import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";
const base="https://musiclink-api.vercel.app/api",nonce=randomBytes(10).toString("hex"),password=randomBytes(24).toString("base64url");
async function call(path,method="GET",body=null,token=""){
 const response=await fetch(base+path,{method,headers:{"Content-Type":"application/json",...(token?{Authorization:"Bearer "+token}:{})},body:body===null?undefined:JSON.stringify(body),signal:AbortSignal.timeout(30000)});
 return {code:response.status,data:await response.json().catch(()=>({}))};
}
const register=async name=>{
 const r=await call("/auth/register","POST",{displayName:name,email:"ci-day5-"+nonce+"-"+name.toLowerCase()+"@example.invalid",password});
 assert.equal(r.code,201,"Account registration");return r.data;
};
const owner=await register("Owner");
const applicant=await register("Applicant");
const projectBody={title:"Original MusicLink Demo",description:"Looking for a singer for the track",genres:["Trap"],requiredRoles:["Vocalist"],requiredSkills:["Singing"],creativeTags:["Dark"],targetDate:"2027-06-12"};
const created=await call("/projects","POST",projectBody,owner.token);
assert.equal(created.code,201,"Project creation");
const id=created.data._id;
assert.equal(created.data.status,"open");
assert.equal(created.data.owner,owner.user.id);
assert.equal(created.data.targetDate.slice(0,10),"2027-06-12");
assert.equal((await call("/projects","POST",{title:"",owner:applicant.user.id},owner.token)).code,400,"Invalid or illegal creation fields");
assert.equal((await call("/projects/"+id,"PATCH",{title:"Hijacked"},applicant.token)).code,403,"Only owner edits");
assert.equal((await call("/projects/"+id,"PATCH",{targetDate:"2026-02-30"},owner.token)).code,400,"Dates validated");
const edited=await call("/projects/"+id,"PATCH",{title:"Edited MusicLink Demo",requiredRoles:["Singer"],targetDate:null},owner.token);
assert.equal(edited.code,200,"Owner edits project");
assert.equal(edited.data.title,"Edited MusicLink Demo");assert.equal(edited.data.targetDate,null);
const open=await call("/projects?status=open","GET",null,applicant.token);
assert.equal(open.code,200);assert.ok(open.data.some(p=>p._id===id),"Open filters show project");
const mine=await call("/projects?mine=true","GET",null,owner.token);
assert.equal(mine.code,200);assert.ok(mine.data.some(p=>p._id===id),"Owner list");
const otherMine=await call("/projects?mine=true","GET",null,applicant.token);
assert.equal(otherMine.code,200);assert.ok(!otherMine.data.some(p=>p._id===id),"Ownership filter");
assert.equal((await call("/projects/"+id+"/apply","POST",{note:"Hi",bad:"data"},applicant.token)).code,400,"Application payload validated");
const applied=await call("/projects/"+id+"/apply","POST",{note:"Singer with five years of experience"},applicant.token);
assert.equal(applied.code,201,"Creator applies");
const appId=applied.data._id;
assert.equal((await call("/projects/"+id+"/apply","POST",{note:"Again"},applicant.token)).code,409,"Duplicates rejected");
assert.equal((await call("/projects/"+id+"/applications","GET",null,applicant.token)).code,403,"Applications owner-only");
const listed=await call("/projects/"+id+"/applications","GET",null,owner.token);
assert.equal(listed.code,200);assert.ok(listed.data.some(a=>a._id===appId),"Owner reviews applications");
const myApps=await call("/me/applications","GET",null,applicant.token);
assert.equal(myApps.code,200);assert.ok(myApps.data.some(a=>a._id===appId),"Creator tracks submission");
assert.equal((await call("/applications/"+appId,"PATCH",{status:"accepted"},applicant.token)).code,403,"Applicant cannot accept");
const accepted=await call("/applications/"+appId,"PATCH",{status:"accepted"},owner.token);
assert.equal(accepted.code,200);assert.equal(accepted.data.status,"accepted");
assert.equal((await call("/applications/"+appId,"PATCH",{status:"rejected"},owner.token)).code,409,"Reviewed application locked");
const closed=await call("/projects/"+id,"PATCH",{status:"closed"},owner.token);
assert.equal(closed.code,200);assert.equal(closed.data.status,"closed");
assert.equal((await call("/projects/"+id+"/apply","POST",{note:"Try"},applicant.token)).code,404,"Closed projects refuse new applications");
const reOpened=await call("/projects/"+id,"PATCH",{status:"open"},owner.token);
assert.equal(reOpened.code,200);assert.equal(reOpened.data.status,"open");
console.log("PASS Day 5 create, edit, owner restrictions, status, applications, filters and validation");
